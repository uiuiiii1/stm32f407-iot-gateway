#ifndef __SDLOG_H
#define __SDLOG_H

#include "stm32f4xx.h"

/*============================================================================
  SD 卡按天 CSV 归档（阶段11 应用层，FatFS 之上）
  - 文件名 YYYYMMDD.CSV（根目录，8.3 短名），行格式：unix,温度x10,湿度x10\r\n
  - 文件常开 + 每 10 条 f_sync + 跨天换文件；掉电最多丢最近 10 条
    （掉电安全的缓存补传由 W25Q64+AT24C64 那层负责，两层互不背锅）
  - 单写者：只允许 STG 任务调用（FatFS 未开重入保护，见 ffconf.h）
  - 失败降级：SD 异常只打一行日志并置禁用，绝不拖累缓存/补传主流程；
    禁用后每 60s 静默重探测（支持拔插卡恢复）
  - RTC 无效（未装电池且未对时）期间写入 NODATE.CSV，时间可信后自动换日文件
  ============================================================================*/

void     SDLOG_Init(void);                        /* 挂载并打开当日文件（STG 初始化时调一次） */
void     SDLOG_Log(uint32_t ts, int16_t t10, uint16_t h10);  /* 追加一条记录（禁用时静默返回） */
uint32_t SDLOG_GetCount(void);                    /* 当日文件已写条数（统计用） */

#endif /* __SDLOG_H */
